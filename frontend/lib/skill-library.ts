// lukethomas skill library: ready-made skills a person can add to any agent with one click.
// Adding one only saves it to that agent (switched on). Like every skill, it is used only when
// the person picks it for a message; it never runs, schedules or approves anything by itself.

export type LibrarySkill = {
  name: string;
  category: LibraryCategory;
  description: string;
  body: string;
};

export type LibraryCategory =
  | "Prospecting"
  | "Outreach"
  | "Sales"
  | "Marketing"
  | "RevOps"
  | "Research"
  | "Operations"
  | "Writing"
  | "Design"
  | "Computer use";

export const LIBRARY_CATEGORIES: LibraryCategory[] = [
  "Prospecting", "Outreach", "Sales", "Marketing", "RevOps", "Research", "Operations", "Writing", "Design", "Computer use",
];

export const LIBRARY_SOURCE = "library";

// Every skill body follows the same shape so agents treat them consistently.
function skill(
  name: string,
  category: LibraryCategory,
  description: string,
  goal: string,
  inputs: string[],
  steps: string[],
  output: string[],
  rules: string[] = [],
): LibrarySkill {
  const list = (items: string[]) => items.map((i) => `- ${i}`).join("\n");
  const numbered = (items: string[]) => items.map((i, n) => `${n + 1}. ${i}`).join("\n");
  const body = [
    `# ${name}`,
    "",
    `## Goal\n${goal}`,
    "",
    `## Inputs to collect first\n${list(inputs)}\nIf anything required is missing, ask for it in one short message before starting.`,
    "",
    `## Steps\n${numbered(steps)}`,
    "",
    `## Output\n${list(output)}`,
    "",
    `## Rules\n${list([
      ...rules,
      "Never send, publish, post, buy or delete anything; draft it and wait for approval.",
      "Say plainly what you could not verify, and cite sources for facts you looked up.",
    ])}`,
  ].join("\n");
  return { name, category, description, body };
}

